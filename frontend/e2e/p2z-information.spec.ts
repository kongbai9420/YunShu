import { expect, test, type Page } from "@playwright/test"

const password = "fake-e2e-password-123"
async function login(page: Page) {
  let response = await page.request.post("/api/auth/login", { data: { username: "admin", password } })
  if (!response.ok()) {
    response = await page.request.post("/api/auth/login", { data: { username: "admin", password: "admin123" } })
    expect(response.ok()).toBeTruthy()
    const csrf = (await page.context().cookies()).find((cookie) => cookie.name === "yunshu_csrf")!.value
    expect((await page.request.post("/api/auth/password", { data: { old_password: "admin123", new_password: password }, headers: { "X-CSRF-Token": csrf } })).ok()).toBeTruthy()
  }
  await page.goto("/#/assets")
  await expect(page.getByRole("heading", { name: "资产管理", exact: true })).toBeVisible()
}

test("新增前获取、单项采用，编辑逐项多选和空字段替换后保存", async ({ page }) => {
  await login(page)
  await page.getByRole("button", { name: "新增资产", exact: true }).first().click()
  const dialog = page.getByRole("dialog", { name: "新增资产", exact: true })
  await dialog.getByLabel("设备地址", { exact: false }).fill("192.0.2.242")
  await dialog.getByLabel("设备用户名", { exact: false }).fill("fake-user")
  await dialog.getByLabel("设备密码", { exact: false }).fill("fake-password")
  await dialog.getByRole("button", { name: "获取设备信息", exact: true }).click()
  await expect(dialog.getByRole("list", { name: "采集字段对比" })).toContainText("fake-inventory-device")
  await expect(dialog.getByLabel(/^名称/, { exact: false })).toHaveValue("")
  await dialog.getByLabel("替换名称", { exact: true }).check()
  await dialog.getByRole("button", { name: "替换选中项（1）", exact: true }).click()
  await expect(dialog.getByLabel(/^名称/)).toHaveValue("fake-inventory-device")
  await expect(dialog.getByLabel("平台", { exact: true })).toHaveValue("")
  await dialog.getByLabel(/^名称/).fill("新增前采集验收")
  const created = page.waitForResponse((response) => response.url().endsWith("/api/assets") && response.request().method() === "POST")
  await dialog.getByRole("button", { name: "创建", exact: true }).click()
  const asset = await (await created).json()
  expect(asset.model).toBe("")
  expect(asset.endpoints[0].ssh_host_key).toBe("ssh-ed25519 AAAAfake-e2e-host")
  const drawer = page.getByRole("dialog")
  await drawer.getByRole("tab", { name: "编辑", exact: true }).click()
  await drawer.getByLabel("品牌", { exact: true }).fill("手工品牌")
  await drawer.getByRole("button", { name: "获取设备信息", exact: true }).click()
  const comparison = drawer.getByRole("region", { name: "设备信息对比" })
  await expect(comparison.getByRole("list")).toContainText("手工品牌")
  await comparison.getByRole("button", { name: "只选空字段", exact: true }).click()
  await expect(comparison.getByLabel("替换品牌", { exact: true })).not.toBeChecked()
  await expect(comparison.getByLabel("替换型号", { exact: true })).toBeChecked()
  await comparison.getByRole("button", { name: "取消选择", exact: true }).click()
  await comparison.getByLabel("替换型号", { exact: true }).check()
  await comparison.getByLabel("替换序列号", { exact: true }).check()
  await comparison.getByRole("button", { name: "替换选中项（2）", exact: true }).click()
  expect((await page.request.get(`/api/assets/${asset.id}`)).ok()).toBeTruthy()
  expect((await (await page.request.get(`/api/assets/${asset.id}`)).json()).model).toBe("")
  await expect(drawer.getByLabel("品牌", { exact: true })).toHaveValue("手工品牌")
  await drawer.getByRole("button", { name: "保存修改", exact: true }).click()
  await expect(drawer.getByText("已保存（修订号 2）。", { exact: true })).toBeVisible()
  const saved = await (await page.request.get(`/api/assets/${asset.id}`)).json()
  expect([saved.name, saved.vendor, saved.model, saved.serial_no, saved.platform]).toEqual(["新增前采集验收", "手工品牌", "Fake Model", "FAKE-SERIAL", ""])
  await comparison.getByRole("button", { name: "全选可替换项", exact: true }).click()
  await comparison.getByRole("button", { name: /^替换选中项/ }).click()
  await drawer.getByRole("button", { name: "撤销修改", exact: true }).click()
  await expect(drawer.getByLabel(/^名称/)).toHaveValue("新增前采集验收")
})

test("获取失败可手填，连接改变丢弃过时结果；窄屏深色与200%字号", async ({ page }) => {
  await login(page)
  await page.setViewportSize({ width: 375, height: 900 })
  await page.emulateMedia({ colorScheme: "dark", reducedMotion: "reduce" })
  await page.evaluate(() => { document.documentElement.style.fontSize = "200%" })
  await page.getByRole("button", { name: "新增资产", exact: true }).first().click()
  const dialog = page.getByRole("dialog", { name: "新增资产", exact: true })
  await dialog.getByLabel("设备地址", { exact: false }).fill("192.0.2.249")
  await dialog.getByLabel("设备用户名", { exact: false }).fill("fake-user")
  await dialog.getByLabel("设备密码", { exact: false }).fill("fake-password")
  await dialog.getByRole("button", { name: "获取设备信息", exact: true }).click()
  await expect(dialog.getByRole("alert")).toContainText("超时")
  await expect(dialog.getByLabel("设备密码", { exact: false })).toHaveValue("fake-password")
  await dialog.getByLabel("设备地址", { exact: false }).fill("192.0.2.248")
  await dialog.getByRole("button", { name: "获取设备信息", exact: true }).click()
  await expect(dialog.getByRole("status")).toContainText("正在连接")
  await dialog.getByLabel("设备地址", { exact: false }).fill("192.0.2.247")
  await expect(dialog.getByRole("list", { name: "采集字段对比" })).toHaveCount(0)
  await dialog.getByRole("button", { name: "获取设备信息", exact: true }).click()
  await expect(dialog.getByRole("list", { name: "采集字段对比" })).toBeVisible()
  await dialog.getByRole("button", { name: "全选可替换项", exact: true }).click()
  await dialog.getByRole("button", { name: "替换选中项（5）", exact: true }).click()
  const width = await dialog.evaluate((element) => ({ client: element.clientWidth, scroll: element.scrollWidth }))
  expect(width.scroll).toBeLessThanOrEqual(width.client + 1)
  await page.screenshot({ path: "test-results/information-mobile.png", fullPage: true })
  await dialog.getByRole("button", { name: "取消", exact: true }).click()
  const assets = await (await page.request.get("/api/assets?q=fake-inventory-device")).json()
  expect(assets.total).toBe(0)
})
